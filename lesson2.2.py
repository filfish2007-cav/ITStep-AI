# ---------------------------------------------------------
# Варіант 1: Zero-shot (без прикладів та роздумів)
# ---------------------------------------------------------

prompt_zero_shot = PromptTemplate.from_template("""
Ти — привітний адміністратор СПА-салону. Твоя задача: порекомендувати клієнту одну найбільш підходящу послугу з нашого списку, спираючись на його запит.
Дай коротку відповідь: назву послуги та одне речення, чому це підійде.

### СПИСОК ПОСЛУГ СПА:
{products_text}

### ЗАПИТ КЛІЄНТА:
{user_query}

### РЕКОМЕНДАЦІЯ:
""")

chain_zero_shot = prompt_zero_shot | llm

response_zero_shot = chain_zero_shot.invoke({
    "products_text": products_data,
    "user_query": user_query
})

print("=== Zero-shot результат ===")
print(response_zero_shot)
print("\n")


# ---------------------------------------------------------
# Варіант 2: Chain of Thoughts (Ланцюг думок)
# ---------------------------------------------------------

prompt_cot = PromptTemplate.from_template("""
Ти — експерт-консультант СПА-салону. Твоя задача: підібрати ідеальну послугу для клієнта на основі його запиту.
Спочатку напиши свій логічний хід думок (проаналізуй проблему клієнта, відкинь невідповідні варіанти, обери найкращий), а потім надай чітку рекомендацію.

### СПИСОК ПОСЛУГ СПА:
{products_text}

### ЗАПИТ КЛІЄНТА:
{user_query}

### ХІД ДУМОК ТА РЕКОМЕНДАЦІЯ:
""")

chain_cot = prompt_cot | llm

response_cot = chain_cot.invoke({
    "products_text": products_data,
    "user_query": user_query
})

print("=== Chain of Thoughts результат ===")
print(response_cot)





