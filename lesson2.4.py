import os
import dotenv

from langchain_google_genai import GoogleGenerativeAI
from langchain_core.prompts import PromptTemplate

dotenv.load_dotenv()
api_key = os.getenv("GEMINI_API_KEY")

llm = GoogleGenerativeAI(
    model='gemini-1.5-flash',
    api_key=api_key,
    temperature=0
)

topic_input = "Вивчення SQL (бази даних)"
audience_input = "Учні 7 класу (12-13 років)"

# ---------------------------------------------------------
# Варіант 1: Zero-shot (без прикладів)
# ---------------------------------------------------------

prompt_zero_shot = PromptTemplate.from_template("""
[РОЛЬ] Ти — досвідчений викладач та методист.
[КОНТЕКСТ] Ситуація така: необхідно розробити навчальну програму, яка відповідає віковим особливостям слухачів.
[ЗАВДАННЯ] Твоя задача — створити структурований план навчального курсу.
[ВХІДНІ ДАНІ] Ось дані:
Тема курсу: {topic}
Цільова аудиторія: {audience}
[ОБМЕЖЕННЯ] Правила: матеріал має бути адаптований для вказаного віку (ігрові елементи, зрозумілі метафори, відсутність надмірної сухої теорії).
[ФОРМАТ] Відповідай у форматі нумерованого списку модулів/уроків без зайвих вступних слів.

ПЛАН КУРСУ:
""")

chain_zero_shot = prompt_zero_shot | llm

response_zero_shot = chain_zero_shot.invoke({
    "topic": topic_input,
    "audience": audience_input
})

print("=== Zero-shot результат ===")
print(response_zero_shot)
print("\n")


# ---------------------------------------------------------
# Варіант 2: Few-shot (з прикладами)
# ---------------------------------------------------------

prompt_few_shot = PromptTemplate.from_template("""
[РОЛЬ] Ти — досвідчений викладач та методист.
[ЗАВДАННЯ] Твоя задача — створити структурований план навчального курсу, адаптований під цільову аудиторію.
[ФОРМАТ] Відповідай у форматі нумерованого списку модулів/уроків без зайвих вступних слів.

### ПРИКЛАД 1
[ВХІДНІ ДАНІ]
Тема курсу: Основи фінансової грамотності
Цільова аудиторія: Діти 10 років
[ПЛАН КУРСУ]:
1. Що таке гроші та звідки вони беруться (гра-симуляція обміну).
2. Кишенькові гроші: як планувати витрати на тиждень.
3. Банк і картки: як безпечно користуватися електронними грошима.
4. Накопичення: як зібрати на омріяну іграшку.

### ПРИКЛАД 2
[ВХІДНІ ДАНІ]
Тема курсу: Docker та контейнеризація
Цільова аудиторія: Професійні розробники (Middle)
[ПЛАН КУРСУ]:
1. Архітектура Docker: Images, Containers, Volumes, Networks.
2. Створення оптимізованих Dockerfile (multistage builds).
3. Оркестрація за допомогою Docker Compose.
4. Best practices безпеки та деплой у CI/CD пайплайнах.

### ПОТОЧНЕ ЗАВДАННЯ
[ВХІДНІ ДАНІ]
Тема курсу: {topic}
Цільова аудиторія: {audience}
[ПЛАН КУРСУ]:
""")

chain_few_shot = prompt_few_shot | llm

response_few_shot = chain_few_shot.invoke({
    "topic": topic_input,
    "audience": audience_input
})

print("=== Few-shot результат ===")
print(response_few_shot)